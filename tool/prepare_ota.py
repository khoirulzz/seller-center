"""Generate runtime configuration from the real, registered Shorebird app ID."""

import os
from pathlib import Path
import uuid


def prepare(root: Path, app_id: str) -> None:
    try:
        parsed = uuid.UUID(app_id)
    except (ValueError, AttributeError) as error:
        raise ValueError("Set SHOREBIRD_APP_ID to the app ID from Shorebird.") from error
    if parsed.int == 0:
        raise ValueError("A placeholder Shorebird app ID cannot be released.")
    pubspec = root / "pubspec.yaml"
    content = pubspec.read_text()
    if "    - shorebird.yaml\n" not in content:
        marker = "  assets:\n"
        if content.count(marker) != 1:
            raise ValueError("Expected exactly one Flutter assets section.")
        content = content.replace(marker, marker + "    - shorebird.yaml\n", 1)
    # A single updater owns checking/downloading so resume/manual checks cannot race
    # with Shorebird's default automatic downloader.
    (root / "shorebird.yaml").write_text(
        "# Generated by tool/prepare_ota.py; the app ID is public.\n"
        f"app_id: {parsed}\nauto_update: false\n"
    )
    pubspec.write_text(content)


if __name__ == "__main__":
    try:
        prepare(Path(__file__).resolve().parent.parent, os.environ.get("SHOREBIRD_APP_ID", ""))
    except ValueError as error:
        raise SystemExit(str(error)) from error
    print("Shorebird runtime configuration prepared.")
